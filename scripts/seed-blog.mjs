// ─── Retry wrapper ────────────────────────────────────────────────────────────

async function retry(fn, retries = 4, delayMs = 3000) {
  for (let i = 0; i < retries; i++) {
    try {
      return await fn()
    } catch (err) {
      const msg = err?.message ?? ''
      const isTransient = msg.includes('terminated') || msg.includes('ECONNRESET') || msg.includes('ECONNREFUSED')
      if (isTransient && i < retries - 1) {
        console.log(`  [retry ${i + 1}/${retries}] connection error, waiting ${delayMs}ms...`)
        await new Promise(r => setTimeout(r, delayMs))
        continue
      }
      throw err
    }
  }
}

